"""Generate the xLights ISF shader for Sky Shooter (shooter.py). Same rules as shooter.render(), in GLSL.

One Shader effect per bar (or a piece of one). The placer simulates the game and passes the bar's starting
state: kick (16-bit slot mask), alive (12-bit), wave, entry, songBeat, plus barBeat/beats for where the
effect sits in the bar. Enemy colours come from the effect's palette (colours 1-3).
"""

from __future__ import annotations

import json

from xlights_mcp.sprites import shooter as g
from xlights_mcp.sprites.shader import MAX_BEATS, MAX_START_BEAT, _rgb

SHADER_NAME = "Sky Shooter.fs"
CODES = ".CYWR"


def isf_header() -> dict:
    return {
        "DESCRIPTION": "xLights Audio2",
        "CREDIT": "xlights-mcp-server Sky Shooter (generated by sprites/shooter_shader.py)",
        "ISFVSN": "2",
        "CATEGORIES": ["xlights-mcp"],
        "INPUTS": [
            {"NAME": "inputImage", "TYPE": "image"},
            {"NAME": "energy", "LABEL": "Bounce to music", "TYPE": "float", "DEFAULT": 1.0, "MIN": 0.0, "MAX": 3.0},
            {"NAME": "kick", "LABEL": "Kick pattern (set by the tool)", "TYPE": "float", "DEFAULT": 4369.0,
             "MIN": 0.0, "MAX": 65535.0},
            {"NAME": "alive", "LABEL": "Enemies alive (set by the tool)", "TYPE": "float",
             "DEFAULT": float(g.ALL_ALIVE), "MIN": 0.0, "MAX": float(g.ALL_ALIVE)},
            {"NAME": "wave", "LABEL": "Wave (set by the tool)", "TYPE": "float", "DEFAULT": 0.0, "MIN": 0.0,
             "MAX": 999.0},
            {"NAME": "entry", "LABEL": "Wave flies in", "TYPE": "bool", "DEFAULT": True},
            {"NAME": "songBeat", "LABEL": "Song beat at bar start", "TYPE": "float", "DEFAULT": 0.0, "MIN": 0.0,
             "MAX": MAX_START_BEAT},
            {"NAME": "barBeat", "LABEL": "Start beat in bar", "TYPE": "float", "DEFAULT": 0.0, "MIN": 0.0, "MAX": 16.0},
            {"NAME": "beats", "LABEL": "Beats in effect", "TYPE": "float", "DEFAULT": 4.0, "MIN": 0.0,
             "MAX": float(MAX_BEATS)},
            {"NAME": "shirt1", "TYPE": "color", "DEFAULT": [0.86, 0.12, 0.16, 1.0]},
            {"NAME": "shirt2", "TYPE": "color", "DEFAULT": [0.12, 0.78, 0.31, 1.0]},
            {"NAME": "shirt3", "TYPE": "color", "DEFAULT": [0.16, 0.47, 1.0, 1.0]},
        ],
    }


def _codes(rows: list[str]) -> list[int]:
    return [CODES.index(ch) for row in rows for ch in row]


def _ints(vals) -> str:
    return ", ".join(str(v) for v in vals)


def build_shader() -> str:
    header = json.dumps(isf_header(), indent=2)
    enemies = [v for kind in g.WAVE_KINDS for frame in g.ENEMY[kind] for v in _codes(frame)]
    sparks = [v for frame in g.SPARK for v in _codes(frame)]
    return f"""/*{header}*/

// Generated by xlights-mcp-server (src/xlights_mcp/sprites/shooter_shader.py). Edit the generator, not this file.

const int PW = {g.PW};
const int PH = {g.PH};
const int COLS = {g.COLS};
const int NE = {g.N_ENEMIES};
const int KILL_ORDER[{g.N_ENEMIES}] = int[]({_ints(g.KILL_ORDER)});
const int SWAY[{len(g.SWAY)}] = int[]({_ints(g.SWAY)});
const int ENEMY[{len(enemies)}] = int[]({_ints(enemies)});
const int SPARK[{len(sparks)}] = int[]({_ints(sparks)});
const int PLAYER[{len(g.PLAYER) * len(g.PLAYER[0])}] = int[]({_ints(_codes(g.PLAYER))});
const vec3 GOLD = {_rgb(g.GOLD)};
const vec3 RED = {_rgb(g.RED)};
const vec3 WHITE = {_rgb(g.WHITE)};
const vec3 BULLET = {_rgb(g.BULLET)};
const vec3 SNOW = {_rgb(g.SNOW)};
const vec3 SPARK_W = {_rgb(g.SPARK_W)};
const vec3 SPARK_Y = {_rgb(g.SPARK_Y)};

int killSlot[NE];
int killEnemy[NE];
int nKills;

bool bitOf(float mask, int b) {{
    return ((int(mask + 0.5) >> b) & 1) == 1;
}}

void buildKills(bool entering) {{
    nKills = 0;
    int t = 0;
    for (int s = 0; s < 16; s++) {{
        if (!bitOf(kick, s) || (entering && s < 4)) continue;
        while (t < NE && !bitOf(alive, KILL_ORDER[t])) t++;
        if (t >= NE) break;
        killSlot[nKills] = s;
        killEnemy[nKills] = KILL_ORDER[t];
        nKills++;
        t++;
    }}
}}

ivec2 enemyPos(int e, int beat, bool entering, float beatInBar, int dip) {{
    int r = e / COLS, c = e % COLS;
    int x = 2 + c * 6 + SWAY[beat % 8];
    int y = 2 + r * 6 + dip;
    if (entering && beatInBar < 1.0) y -= (4 - int(beatInBar * 4.0)) * 3;
    return ivec2(x, y);
}}

int playerX(int slot, int beat) {{
    int target = -1;
    for (int k = 0; k < NE; k++) {{
        if (k >= nKills) break;
        if (killSlot[k] >= slot) {{ target = killEnemy[k]; break; }}
    }}
    if (target < 0 && nKills > 0) target = killEnemy[nKills - 1];
    if (target < 0) return 16 + SWAY[beat % 8] * 4;
    return enemyPos(target, beat, false, 1.0, 0).x + 2 - 3;
}}

uint hashFlake(int flake) {{
    return uint(flake) * 2654435761u;
}}

bool inSprite(ivec2 p, ivec2 at, int w, int h) {{
    return p.x >= at.x && p.y >= at.y && p.x < at.x + w && p.y < at.y + h;
}}

vec4 game(ivec2 p, float beatInBar, int dip) {{
    int q = int(floor(beatInBar * 16.0));
    int slot = q / 4, sub = q % 4;
    int beat = int(songBeat + 0.5) + int(floor(beatInBar));
    int kind = int(wave + 0.5) % 3;

    ivec2 pp = ivec2(playerX(slot, beat), {g.PLAYER_Y});
    if (inSprite(p, pp, {len(g.PLAYER[0])}, {len(g.PLAYER)})) {{
        int c = PLAYER[(p.y - pp.y) * {len(g.PLAYER[0])} + p.x - pp.x];
        if (c == 4) return vec4(RED, 1.0);
        if (c == 2) return vec4(GOLD, 1.0);
        if (c == 3) return vec4(WHITE, 1.0);
    }}

    for (int k = 0; k < NE; k++) {{                        // the shot that lands on the kick
        if (k >= nKills) break;
        int s = killSlot[k];
        if (s >= 1 && slot == s - 1) {{
            ivec2 ep = enemyPos(killEnemy[k], beat, false, 1.0, dip);
            int top = {g.GUN_Y} - (({g.GUN_Y} - (ep.y + 5)) * sub) / 4;
            if (p.x == ep.x + 2 && (p.y == top || p.y == top + 1)) return vec4(BULLET, 1.0);
        }}
    }}
    for (int s0 = 0; s0 < 16; s0 += 4) {{                   // a shot on every beat with no kill near it
        if (slot < s0 || slot > s0 + 1) continue;
        bool near = false;
        for (int k = 0; k < NE; k++) {{
            if (k >= nKills) break;
            if (killSlot[k] >= s0 && killSlot[k] <= s0 + 2) near = true;
        }}
        if (near) continue;
        int top = {g.GUN_Y} - ((slot - s0) * 4 + sub) * 2;
        int bx = playerX(s0, beat) + 3;
        if (p.x == bx && (p.y == top || p.y == top + 1)) return vec4(BULLET, 1.0);
    }}

    for (int k = NE - 1; k >= 0; k--) {{                    // sparkle bursts (later ones on top)
        if (k >= nKills) continue;
        int s = killSlot[k];
        if (slot != s && slot != s + 1) continue;
        ivec2 ep = enemyPos(killEnemy[k], beat, false, 1.0, dip);
        if (inSprite(p, ep, 5, 5)) {{
            int c = SPARK[(slot - s) * 25 + (p.y - ep.y) * 5 + p.x - ep.x];
            if (c == 3) return vec4(SPARK_W, 1.0);
            if (c == 2) return vec4(SPARK_Y, 1.0);
        }}
    }}

    for (int e = NE - 1; e >= 0; e--) {{
        if (!bitOf(alive, e)) continue;
        bool gone = false;
        for (int k = 0; k < NE; k++) {{
            if (k >= nKills) break;
            if (killEnemy[k] == e && slot >= killSlot[k]) gone = true;
        }}
        if (gone) continue;
        ivec2 ep = enemyPos(e, beat, entry, beatInBar, dip);
        if (inSprite(p, ep, 5, 5)) {{
            int c = ENEMY[(kind * 2 + beat % 2) * 25 + (p.y - ep.y) * 5 + p.x - ep.x];
            int row = (e / COLS + int(wave + 0.5)) % 3;
            vec3 col = row == 0 ? shirt1.rgb : (row == 1 ? shirt2.rgb : shirt3.rgb);
            if (c == 1) return vec4(col, 1.0);
            if (c == 2) return vec4(GOLD, 1.0);
            if (c == 3) return vec4(WHITE, 1.0);
        }}
    }}

    int qs = int(songBeat + 0.5) * 16 + q;
    for (int fl = {g.SNOW_FLAKES - 1}; fl >= 0; fl--) {{
        uint h = hashFlake(fl);
        int x = int(h % uint(PW));
        int speed = 1 + int((h >> 8) % 3u);
        int y = (int((h >> 16) % uint(PH)) + (qs * speed) / 16) % PH;
        if (p.x == x && p.y == y) return vec4(SNOW, 1.0);
    }}
    return vec4(0.0);
}}

void main() {{
    vec2 rs = RENDERSIZE;
    vec2 px = floor(gl_FragCoord.xy);
    px.y = rs.y - 1.0 - px.y;
    int scale = max(1, min(int(rs.x) / PW, int(rs.y) / PH));
    vec2 origin = floor((rs - vec2(float(PW * scale), float(PH * scale))) / 2.0);
    vec2 gp = floor((px - origin) / float(scale));
    if (gp.x < 0.0 || gp.y < 0.0 || gp.x >= float(PW) || gp.y >= float(PH)) {{
        gl_FragColor = vec4(0.0);
        return;
    }}
    float beatInBar = barBeat + TIME / max(XL_DURATION, 0.001) * max(beats, 0.01);
    float f = fract(beatInBar);
    float loud = clamp(texture(inputImage, vec2(0.5, 0.5)).x * energy, 0.0, 1.0);
    int dip = min(1, int(floor(loud * 1.5 * sin(3.14159 * f) + 0.5)));
    buildKills(entry);
    gl_FragColor = game(ivec2(gp), beatInBar, dip);
}}
"""


def shooter_settings(path: str, st: g.BarState, bar_beat: float, beats: float, energy: float = 1.0) -> dict[str, str]:
    if not 0 < beats <= MAX_BEATS:
        raise ValueError(f"{beats} beats in one effect; the shader takes up to {MAX_BEATS}")
    if st.song_beat > MAX_START_BEAT:
        raise ValueError(f"song beat {st.song_beat} is past the shader's limit of {MAX_START_BEAT:.0f}")
    return {
        "E_0FILEPICKERCTRL_IFS": path,
        "E_SLIDER_SHADERXYZZY_energy": str(int(round(energy * 100))),
        "E_SLIDER_SHADERXYZZY_kick": str(st.kick * 100),
        "E_SLIDER_SHADERXYZZY_alive": str(st.alive * 100),
        "E_SLIDER_SHADERXYZZY_wave": str(st.wave * 100),
        "E_CHECKBOX_SHADERXYZZY_entry": "1" if st.entry else "0",
        "E_SLIDER_SHADERXYZZY_songBeat": str(st.song_beat * 100),
        "E_SLIDER_SHADERXYZZY_barBeat": str(int(round(bar_beat * 100))),
        "E_SLIDER_SHADERXYZZY_beats": str(int(round(beats * 100))),
        "E_SLIDER_Shader_Speed": "100",
        "E_TEXTCTRL_Shader_LeadIn": "0",
        "E_TEXTCTRL_Shader_Offset_X": "0",
        "E_TEXTCTRL_Shader_Offset_Y": "0",
        "E_TEXTCTRL_Shader_Zoom": "0",
    }
