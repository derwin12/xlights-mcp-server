"""Generate an xLights ISF shader that draws the dance crew on the GPU.

The poses and routines are written into the shader from dancers.POSES / ROUTINES,
so the GIF and shader versions share one set of moves. The shader:
  * works out the beat from TIME / XL_DURATION * beats + startBeat, so placing one
    Shader effect per bar (with startBeat = beats since the routine started) keeps
    every pose on the Beats track;
  * eases each limb into the next pose near the end of the beat (smoothing);
  * dips the body on each beat by an amount that follows the song's loudness
    ("xLights Audio2" mode puts the level in the image input);
  * takes shirt / dress colours from the effect's palette (colours 1-3);
  * stays pixel art: everything is drawn on a 13x17 grid per dancer, scaled up by
    whole LEDs, and pixels outside the dancers are transparent;
  * can draw the stage (stage.py): floor, beat-swapping spotlights, sparkles. Sparkles use the same
    integer hash as the GIF version, so both draw the same stage.
"""

from __future__ import annotations

import json

from xlights_mcp.sprites import dancers as d
from xlights_mcp.sprites import stage as S

SHADER_NAME = "Dance Crew.fs"
ROUTINE_NAMES = list(d.ROUTINES)
FIGURE_LABELS = ["Male", "Female", "Mixed"]
STYLE_LABELS = ["Unison", "Mirror", "Canon"]
DANCER_LABELS = ["Fit"] + [str(i) for i in range(1, 10)]
MAX_START_BEAT = 2000.0
MAX_BEATS = 64       # per-bar placement uses ~4; per-section placement splits longer sections
BEATS_PER_ROUTINE = 16


def _pose_floats(p: d.Pose) -> list[float]:
    pts = [p.elbow_l, p.hand_l, p.elbow_r, p.hand_r, p.knee_l, p.foot_l, p.knee_r, p.foot_r, p.body]
    return [float(v) for pt in pts for v in pt] + [float(p.slide)]


def _routine_indices(names: list[str]) -> list[int]:
    out = []
    for r in ROUTINE_NAMES:
        flat = [p for bar in d.ROUTINES[r] for p in bar]
        if len(flat) != BEATS_PER_ROUTINE:
            raise ValueError(f"routine {r} has {len(flat)} beats; the shader expects {BEATS_PER_ROUTINE}")
        out += [names.index(p) for p in flat]
    return out


def isf_header() -> dict:
    return {
        "DESCRIPTION": "xLights Audio2",
        "CREDIT": "xlights-mcp-server dance crew (generated by sprites/shader.py)",
        "ISFVSN": "2",
        "CATEGORIES": ["xlights-mcp"],
        "INPUTS": [
            {"NAME": "inputImage", "TYPE": "image"},
            {"NAME": "routine", "LABEL": "Routine", "TYPE": "long", "DEFAULT": 0,
             "VALUES": list(range(len(ROUTINE_NAMES))), "LABELS": [r.title() for r in ROUTINE_NAMES]},
            {"NAME": "figure", "LABEL": "Figure", "TYPE": "long", "DEFAULT": 0,
             "VALUES": [0, 1, 2], "LABELS": FIGURE_LABELS},
            {"NAME": "style", "LABEL": "Style", "TYPE": "long", "DEFAULT": 0,
             "VALUES": [0, 1, 2], "LABELS": STYLE_LABELS},
            {"NAME": "stage", "LABEL": "Stage", "TYPE": "bool", "DEFAULT": False},
            # xLights shows no control for plain "long" inputs, so counts are a choice list or a slider.
            {"NAME": "dancers", "LABEL": "Dancers", "TYPE": "long", "DEFAULT": 0,
             "VALUES": list(range(10)), "LABELS": DANCER_LABELS},
            {"NAME": "beats", "LABEL": "Beats in effect", "TYPE": "float", "DEFAULT": 4.0, "MIN": 0.0, "MAX": float(MAX_BEATS)},
            {"NAME": "startBeat", "LABEL": "Start beat", "TYPE": "float", "DEFAULT": 0.0, "MIN": 0.0, "MAX": MAX_START_BEAT},
            {"NAME": "smoothing", "LABEL": "Smooth moves", "TYPE": "float", "DEFAULT": 0.35, "MIN": 0.0, "MAX": 1.0},
            {"NAME": "energy", "LABEL": "Bounce to music", "TYPE": "float", "DEFAULT": 1.0, "MIN": 0.0, "MAX": 3.0},
            {"NAME": "shirt1", "TYPE": "color", "DEFAULT": [0.59, 0.24, 0.9, 1.0]},
            {"NAME": "shirt2", "TYPE": "color", "DEFAULT": [0.94, 0.2, 0.08, 1.0]},
            {"NAME": "shirt3", "TYPE": "color", "DEFAULT": [0.08, 0.78, 0.75, 1.0]},
        ],
    }


def _glsl_floats(vals: list[float]) -> str:
    return ", ".join(f"{v:.1f}" for v in vals)


def _rgb(c) -> str:
    return "vec3({:.4f}, {:.4f}, {:.4f})".format(*(v / 255 for v in c))


def stage_glsl() -> str:
    """GLSL for the stage (floor, beat-swapping spotlights, sparkles), shared by the crew and band shaders.

    Needs uniforms shirt1..shirt3 (light colours) declared by the shader's inputs.
    """
    return f"""const vec3 FLOOR_C = {_rgb(S.FLOOR)};
const vec3 SHINE_C = {_rgb(S.FLOOR_SHINE)};
const vec3 SPARKLES[3] = vec3[]({", ".join(_rgb(c) for c in S.SPARKLES)});
const int CYCLE = {S.CYCLE};
const float BEAM_LEVEL = {S.BEAM_LEVEL};

uint hash32(uint n) {{
    n = (n ^ 61u) ^ (n >> 16);
    n *= 9u;
    n ^= n >> 4;
    n *= 0x27D4EB2Du;
    n ^= n >> 15;
    return n;
}}

vec3 shirtOf(int j) {{
    return j % 3 == 0 ? shirt1.rgb : (j % 3 == 1 ? shirt2.rgb : shirt3.rgb);
}}

// The stage behind the crew at matrix pixel px (y down); alpha 0 where it is dark.
vec4 stagePixel(vec2 px, vec2 rs, int scale, vec2 origin, vec2 crew, int backups, int beat, int sub) {{
    float floorY = rs.y - float(scale);
    int cycle = beat % CYCLE;
    if (px.y >= floorY) {{
        int run = max(2, scale * 2);
        float pos = float(((cycle * 2 + sub) * run) % max(int(crew.x), 1));
        if (px.x >= origin.x + pos && px.x < min(origin.x + pos + float(run), rs.x)) return vec4(SHINE_C, 1.0);
        if (px.x >= max(0.0, origin.x - float(scale)) && px.x < min(rs.x, origin.x + crew.x + float(scale)))
            return vec4(FLOOR_C, 1.0);
        return vec4(0.0);
    }}
    uint seed = uint(cycle * 31 + sub * 7) + uint(rs.x) * 1000u + uint(rs.y);
    int count = max(2, int(rs.x) * int(rs.y) / 160);
    vec4 spark = vec4(0.0);
    for (int s = 0; s < count; s++) {{
        uint v = hash32(seed * 64u + uint(s));
        if (float(v % uint(rs.x)) == px.x && float((v >> 16) % uint(max(1.0, floorY))) == px.y)
            spark = vec4(SPARKLES[int((v >> 8) % 3u)], 1.0);
    }}
    if (spark.a > 0.0) return spark;
    vec3 lights[3];
    int nl = 0;
    for (int j = 0; j < 3 && j < backups; j++) {{
        vec3 c = shirtOf(j);
        bool seen = false;
        for (int q = 0; q < nl; q++) if (lights[q] == c) seen = true;
        if (!seen) lights[nl++] = c;
    }}
    if (nl == 0) {{
        lights[0] = {_rgb(d.SHIRTS["purple"])};
        lights[1] = {_rgb(d.SHIRTS["teal"])};
        nl = 2;
    }}
    int lw = max(1, scale);
    for (int side = 1; side >= 0; side--) {{               // right lamp over left
        float lx = side == 0 ? 0.0 : rs.x - 1.0;
        vec3 col = lights[(beat + side) % nl];
        if (px.y < float(lw)) {{
            if (side == 0 ? px.x < float(lw * 2) : px.x > lx - float(lw * 2)) return vec4(col, 1.0);
            continue;
        }}
        float target = origin.x + crew.x * (side == 0 ? 0.3 : 0.7);
        float t = px.y / max(floorY, 1.0);
        float cx = lx + (target - lx) * t;
        float spread = 0.5 + t * crew.x * 0.12;
        if (px.x >= float(int(cx - spread)) && px.x <= float(int(cx + spread))) {{
            vec3 c255 = floor(col * 255.0 + 0.5);
            return vec4(max(floor(c255 * BEAM_LEVEL), vec3(12.0)) / 255.0, 1.0);
        }}
    }}
    return vec4(0.0);
}}"""


def build_shader() -> str:
    names = list(d.POSES)
    poses = [v for n in names for v in _pose_floats(d.POSES[n])]
    routines = _routine_indices(names)
    hair = [d.HAIR[h] for h in ("blonde", "pink", "auburn", "violet")]
    header = json.dumps(isf_header(), indent=2)
    return f"""/*{header}*/

// Generated by xlights-mcp-server (src/xlights_mcp/sprites/shader.py). Edit the generator, not this file.

const int NPOSES = {len(names)};
const int POSE_LEN = 19;
const int STAND = {names.index("stand")};
const int NROUTINES = {len(ROUTINE_NAMES)};
const int ROUTINE_LEN = {BEATS_PER_ROUTINE};
const float POSES[{len(poses)}] = float[]({_glsl_floats(poses)});
const int ROUTINES[{len(routines)}] = int[]({", ".join(map(str, routines))});

const vec3 BONE = {_rgb(d.BONE)};
const vec3 JOINT = {_rgb(d.JOINT)};
const vec3 HAIR[4] = vec3[]({", ".join(_rgb(c) for c in hair)});


vec2 joint(int pose, int j) {{
    int b = pose * POSE_LEN + j * 2;
    return vec2(POSES[b], POSES[b + 1]);
}}

float slideOf(int pose) {{
    return POSES[pose * POSE_LEN + 18];
}}

int poseAt(int r, int k) {{
    if (k < 0) return STAND;
    return ROUTINES[r * ROUTINE_LEN + k % ROUTINE_LEN];
}}

// Round to the nearest whole pixel; an exact half goes toward the line's end, as Bresenham does.
float roundTo(float v, float dir) {{
    return dir > 0.0 ? floor(v + 0.5) : ceil(v - 0.5);
}}

// One pixel of a thin line, rasterised along its major axis like Bresenham.
bool onSeg(vec2 p, vec2 a, vec2 b) {{
    vec2 d = b - a;
    if (abs(d.x) < 0.001 && abs(d.y) < 0.001) return all(equal(p, floor(a + 0.5)));
    if (abs(d.x) >= abs(d.y)) {{
        if (p.x < floor(min(a.x, b.x) + 0.5) || p.x > floor(max(a.x, b.x) + 0.5)) return false;
        float y = a.y + (p.x - a.x) * d.y / d.x;
        return p.y == roundTo(y, d.y);
    }}
    if (p.y < floor(min(a.y, b.y) + 0.5) || p.y > floor(max(a.y, b.y) + 0.5)) return false;
    float x = a.x + (p.y - a.y) * d.x / d.y;
    return p.x == roundTo(x, d.x);
}}

bool at(vec2 p, vec2 q) {{
    return all(equal(p, floor(q + 0.5)));
}}

// Colour of sprite pixel p (13x17 grid, y down) for one dancer, or alpha 0.
vec4 dancer(vec2 p, vec2 J[8], vec2 body, bool female, vec3 shirt, bool band, vec3 hair) {{
    vec2 q = p - body;                       // body-relative (head, torso, arms)
    vec3 dark = shirt * 0.6;
    // head: hair / band / bow, skull, neck
    if (q.y == 0.0 && q.x >= 4.0 && q.x <= 8.0) {{
        if (female) return vec4(hair, 1.0);
        if (band) return vec4(shirt, 1.0);
    }}
    if (female && q.y == 0.0 && (q.x == 9.0 || q.x == 10.0)) return vec4(shirt, 1.0);
    if (q.y == 0.0 && q.x >= 4.0 && q.x <= 8.0) return vec4(BONE, 1.0);
    if (q.y == 1.0 && (q.x == 4.0 || q.x == 6.0 || q.x == 8.0)) return vec4(BONE, 1.0);
    if (q.y == 2.0 && q.x >= 4.0 && q.x <= 8.0) return vec4(BONE, 1.0);
    if (q.y == 3.0 && q.x >= 5.0 && q.x <= 7.0) return vec4(BONE, 1.0);
    if (q.x == 6.0 && q.y == 4.0) return vec4(BONE, 1.0);
    // arms (right over left): sleeve at the shoulder, grey elbow, bone
    for (int s = 1; s >= 0; s--) {{
        vec2 sh = vec2(s == 0 ? 4.0 : 8.0, 5.0);
        vec2 el = J[s * 2] , ha = J[s * 2 + 1];
        if (at(q, sh)) return vec4(shirt, 1.0);
        if (at(q, el)) return vec4(JOINT, 1.0);
        if (onSeg(q, sh, el) || onSeg(q, el, ha)) return vec4(BONE, 1.0);
    }}
    if (female) {{
        if ((q.x == 3.0 || q.x == 9.0) && q.y >= 1.0 && q.y <= 4.0) return vec4(hair, 1.0);
        if (q.y == 8.0 && q.x >= 5.0 && q.x <= 7.0) return vec4(q.x == 5.0 ? dark : shirt, 1.0);
        if (q.y == 9.0 && q.x >= 4.0 && q.x <= 8.0) return vec4(q.x == 4.0 ? dark : shirt, 1.0);
        if (q.y == 10.0 && q.x >= 3.0 && q.x <= 9.0) return vec4(q.x == 3.0 ? dark : shirt, 1.0);
    }}
    if (q.y >= 5.0 && q.y <= 8.0 && q.x >= 5.0 && q.x <= 7.0) return vec4(q.x == 5.0 ? dark : shirt, 1.0);
    if (q.y == 9.0 && q.x >= 5.0 && q.x <= 7.0) return vec4(BONE, 1.0);
    // legs (right over left): toe, grey knee, bone; hips move with the body, feet stay put
    for (int s = 1; s >= 0; s--) {{
        vec2 hip = vec2(s == 0 ? 5.0 : 7.0, 10.0) + body;
        vec2 kn = J[4 + s * 2], ft = J[5 + s * 2];
        if (at(p, ft + vec2(s == 0 ? -1.0 : 1.0, 0.0))) return vec4(BONE, 1.0);
        if (at(p, kn)) return vec4(JOINT, 1.0);
        if (onSeg(p, hip, kn) || onSeg(p, kn, ft)) return vec4(BONE, 1.0);
    }}
    return vec4(0.0);
}}

float dist2(vec3 a, vec3 b) {{
    vec3 d = (a - b) * 255.0;
    return dot(d, d);
}}

{stage_glsl()}

// One crew member at sprite pixel sp; j is the dancer's place in the line.
vec4 crewPixel(vec2 sp, float beat0, int dip) {{
    int j = int(sp.x) / 13;
    vec2 p = vec2(mod(sp.x, 13.0), sp.y);
    bool mirrored = style == 1 && j % 2 == 1;

    float beatPos = beat0 - (style == 2 ? float(j) : 0.0);
    int k = int(floor(beatPos));
    float f = beatPos - float(k);
    int r = clamp(routine, 0, NROUTINES - 1);
    int pa = poseAt(r, k), pb = poseAt(r, k + 1);
    float t = smoothing < 0.01 ? 0.0 : smoothstep(1.0 - smoothing, 1.0, f);

    vec2 J[8];
    for (int q = 0; q < 8; q++) J[q] = mix(joint(pa, q), joint(pb, q), t);
    vec2 body = floor(mix(joint(pa, 8), joint(pb, 8), t) + 0.5);
    float slide = floor(mix(slideOf(pa), slideOf(pb), t) + 0.5);
    if (mirrored) {{                           // flip the pose (left and right limbs swap), not the drawing
        for (int q = 0; q < 8; q += 2) {{
            int o = (q / 2) % 2 == 0 ? q + 2 : q - 2;
            vec2 e = J[q], h = J[q + 1];
            if (o > q) {{
                J[q] = vec2(12.0 - J[o].x, J[o].y); J[q + 1] = vec2(12.0 - J[o + 1].x, J[o + 1].y);
                J[o] = vec2(12.0 - e.x, e.y); J[o + 1] = vec2(12.0 - h.x, h.y);
            }}
        }}
        body.x = -body.x;
        slide = -slide;
    }}
    body.y += float(dip);
    p.x -= slide;

    bool female = figure == 1 || (figure == 2 && j % 2 == 0);
    vec3 shirt = shirtOf(j);
    vec3 hair = HAIR[j % 4];
    for (int h = 0; h < 4; h++) {{
        if (dist2(hair, shirt) > 120.0 * 120.0) break;
        hair = HAIR[(j + h + 1) % 4];
    }}
    return dancer(p, J, body, female, shirt, j % 2 == 0, hair);
}}

void main() {{
    vec2 rs = RENDERSIZE;
    vec2 px = floor(gl_FragCoord.xy);
    px.y = rs.y - 1.0 - px.y;                 // y down, like the sprites

    int n = dancers;
    int scale;
    if (n > 0) {{
        scale = max(1, min(int(rs.y) / 17, int(rs.x) / (13 * n)));
    }} else {{
        scale = max(1, min(int(rs.y) / 17, int(rs.x) / 13));
        n = max(1, min(9, int(rs.x) / (13 * scale)));
    }}
    vec2 crew = vec2(float(n * 13 * scale), float(17 * scale));
    vec2 origin = stage ? vec2(floor((rs.x - crew.x) / 2.0), rs.y - crew.y) : floor((rs - crew) / 2.0);

    float beat0 = startBeat + TIME / max(XL_DURATION, 0.001) * max(beats, 0.01);
    int k0 = int(floor(beat0));
    float f0 = beat0 - float(k0);
    float loud = clamp(texture(inputImage, vec2(0.5, 0.5)).x * energy, 0.0, 1.0);
    int dip = int(floor(loud * 1.5 * sin(3.14159 * f0) + 0.5));

    vec4 c = vec4(0.0);
    vec2 sp = floor((px - origin) / float(scale));
    if (sp.x >= 0.0 && sp.y >= 0.0 && sp.x < float(n * 13) && sp.y < 17.0) c = crewPixel(sp, beat0, dip);
    if (c.a == 0.0 && stage) c = stagePixel(px, rs, scale, origin, crew, n, k0, f0 >= 0.5 ? 1 : 0);
    gl_FragColor = c;
}}
"""


def shader_settings(path: str, routine: str, figure: str, style: str, start_beat: float, beats: float,
                    dancers: int = 0, smoothing: float = 0.35, energy: float = 1.0,
                    stage: bool = False) -> dict[str, str]:
    """Effect settings for one Shader effect running this shader (float sliders are stored x100)."""
    if not 0 < beats <= MAX_BEATS:
        raise ValueError(f"{beats} beats in one effect; the shader takes 1 to {MAX_BEATS}")
    if start_beat > MAX_START_BEAT:
        raise ValueError(f"start beat {start_beat} is past the shader's limit of {MAX_START_BEAT:.0f}")
    return {
        "E_0FILEPICKERCTRL_IFS": path,
        "E_CHOICE_SHADERXYZZY_routine": routine.title(),
        "E_CHOICE_SHADERXYZZY_figure": figure.title(),
        "E_CHOICE_SHADERXYZZY_style": style.title(),
        "E_CHECKBOX_SHADERXYZZY_stage": "1" if stage else "0",
        "E_CHOICE_SHADERXYZZY_dancers": DANCER_LABELS[dancers] if 0 <= dancers <= 9 else "Fit",
        "E_SLIDER_SHADERXYZZY_beats": str(int(round(beats * 100))),
        "E_SLIDER_SHADERXYZZY_startBeat": str(int(round(start_beat * 100))),
        "E_SLIDER_SHADERXYZZY_smoothing": str(int(round(smoothing * 100))),
        "E_SLIDER_SHADERXYZZY_energy": str(int(round(energy * 100))),
        "E_SLIDER_Shader_Speed": "100",
        "E_TEXTCTRL_Shader_LeadIn": "0",
        "E_TEXTCTRL_Shader_Offset_X": "0",
        "E_TEXTCTRL_Shader_Offset_Y": "0",
        "E_TEXTCTRL_Shader_Zoom": "0",
    }
