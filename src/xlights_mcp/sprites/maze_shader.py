"""Generate the xLights ISF shader for Maze Chase (maze.py). Same rules as maze.render(), in GLSL.

One Shader effect per bar (or a piece of one). The placer passes the runner's step count at the bar's start
(startStep) and the bar's kick slots; the maze, tour and sprites are baked in. Wall and scarf colours come
from the effect's palette (colours 1-3).
"""

from __future__ import annotations

import json

from xlights_mcp.sprites import maze as m
from xlights_mcp.sprites.shader import MAX_BEATS, _rgb

SHADER_NAME = "Maze Chase.fs"
MAX_STEP = 99999.0


def isf_header() -> dict:
    return {
        "DESCRIPTION": "xLights Audio2",
        "CREDIT": "xlights-mcp-server Maze Chase (generated by sprites/maze_shader.py)",
        "ISFVSN": "2",
        "CATEGORIES": ["xlights-mcp"],
        "INPUTS": [
            {"NAME": "inputImage", "TYPE": "image"},
            {"NAME": "energy", "LABEL": "Bounce to music", "TYPE": "float", "DEFAULT": 1.0, "MIN": 0.0, "MAX": 3.0},
            {"NAME": "kick", "LABEL": "Kick pattern (set by the tool)", "TYPE": "float", "DEFAULT": 4369.0,
             "MIN": 0.0, "MAX": 65535.0},
            {"NAME": "startStep", "LABEL": "Runner step at bar start (set by the tool)", "TYPE": "float",
             "DEFAULT": 0.0, "MIN": 0.0, "MAX": MAX_STEP},
            {"NAME": "barBeat", "LABEL": "Start beat in bar", "TYPE": "float", "DEFAULT": 0.0, "MIN": 0.0, "MAX": 16.0},
            {"NAME": "beats", "LABEL": "Beats in effect", "TYPE": "float", "DEFAULT": 4.0, "MIN": 0.0,
             "MAX": float(MAX_BEATS)},
            {"NAME": "shirt1", "TYPE": "color", "DEFAULT": [0.86, 0.12, 0.16, 1.0]},
            {"NAME": "shirt2", "TYPE": "color", "DEFAULT": [0.12, 0.78, 0.31, 1.0]},
            {"NAME": "shirt3", "TYPE": "color", "DEFAULT": [0.16, 0.47, 1.0, 1.0]},
        ],
    }


def _ints(vals) -> str:
    return ", ".join(str(v) for v in vals)


def build_shader() -> str:
    header = json.dumps(isf_header(), indent=2)
    walls = [1 if m.WALLS[y][x] else 0 for y in range(m.PH) for x in range(m.PW)]
    first = [m.FIRST_VISIT[c] for c in range(m.CW * m.CH)]
    sprite = lambda rows, codes: [codes.index(ch) for row in rows for ch in row]  # noqa: E731
    return f"""/*{header}*/

// Generated by xlights-mcp-server (src/xlights_mcp/sprites/maze_shader.py). Edit the generator, not this file.

const int PW = {m.PW};
const int PH = {m.PH};
const int CW = {m.CW};
const int NCELLS = {m.CW * m.CH};
const int LAP = {m.LAP};
const int WALLS[{len(walls)}] = int[]({_ints(walls)});
const int TOUR[{m.LAP}] = int[]({_ints(m.TOUR)});
const int FIRST_VISIT[{len(first)}] = int[]({_ints(first)});
const int RUNNER[9] = int[]({_ints(sprite(m.RUNNER, ".GI"))});
const int SNOWMEN[9] = int[]({_ints(sprite(m.SNOWMEN, ".HWS"))});
const int GAPS[{len(m.CHASE_GAPS)}] = int[]({_ints(m.CHASE_GAPS)});
const vec3 WHITE = {_rgb(m.WHITE)};
const vec3 GINGER = {_rgb(m.GINGER)};
const vec3 ICING = {_rgb(m.ICING)};
const vec3 SNOWMAN = {_rgb(m.SNOWMAN)};
const vec3 HAT = {_rgb(m.HAT)};
const vec3 MINT_RED = {_rgb(m.MINT_RED)};
const vec3 SPARK = {_rgb(m.SPARK)};

bool bitOf(float mask, int b) {{
    return b >= 0 && b < 16 && ((int(mask + 0.5) >> b) & 1) == 1;
}}

ivec2 cellXY(int c) {{
    return ivec2({m.OX} + 1 + (c % CW) * 4, {m.OY} + 1 + (c / CW) * 4);
}}

ivec2 posAt(int stepQ) {{
    int k = stepQ / 4, sub = stepQ % 4;
    ivec2 a = cellXY(TOUR[k % LAP]), b = cellXY(TOUR[(k + 1) % LAP]);
    return a + ((b - a) * sub) / 4;
}}

int runnerQ(int startStep, int q) {{
    int slot = q / 4, sub = q % 4;
    int steps = slot;
    for (int s = 0; s < 16; s++) if (s < slot && bitOf(kick, s)) steps++;
    int base = (startStep + steps) * 4;
    return bitOf(kick, slot) ? base + sub * 2 : base + sub;
}}

vec3 pal(int i) {{
    i = i % 3;
    return i == 0 ? shirt1.rgb : (i == 1 ? shirt2.rgb : shirt3.rgb);
}}

vec4 game(ivec2 p, float beatInBar, int dip) {{
    int q = int(floor(beatInBar * 16.0));
    int slot = q / 4;
    int rq = runnerQ(int(startStep + 0.5), q);
    int lap = (rq / 4) / LAP, inLap = (rq / 4) % LAP;

    ivec2 r = posAt(rq);
    if (bitOf(kick, slot)) {{                                   // dash sparkle
        if (p == r + ivec2(-1, 1) || p == r + ivec2(3, 1) || p == r + ivec2(1, -1) || p == r + ivec2(1, 3))
            return vec4(SPARK, 1.0);
    }}
    ivec2 d = p - r;
    if (d.x >= 0 && d.y >= 0 && d.x < 3 && d.y < 3) {{
        int c = RUNNER[d.y * 3 + d.x];
        if (c == 1) return vec4(GINGER, 1.0);
        if (c == 2) return vec4(ICING, 1.0);
    }}
    for (int i = {len(m.CHASE_GAPS) - 1}; i >= 0; i--) {{
        int sq = rq - GAPS[i] * 4;
        if (sq < 0) continue;
        ivec2 s = posAt(sq) - ivec2(0, dip);
        ivec2 e = p - s;
        if (e.x >= 0 && e.y >= 0 && e.x < 3 && e.y < 3) {{
            int c = SNOWMEN[e.y * 3 + e.x];
            if (c == 1) return vec4(HAT, 1.0);
            if (c == 2) return vec4(SNOWMAN, 1.0);
            if (c == 3) return vec4(pal(i + 1), 1.0);
        }}
    }}
    if (p.x >= {m.OX} + 1 && p.y >= {m.OY} + 1) {{                 // peppermints at cell centres
        int cx = (p.x - {m.OX} - 1) / 4, cy = (p.y - {m.OY} - 1) / 4;
        if (cx < CW && cy < {m.CH}) {{
            int c = cy * CW + cx;
            if (cellXY(c) + ivec2(1, 1) == p && FIRST_VISIT[c] > inLap)
                return vec4(c % 2 == 0 ? MINT_RED : WHITE, 1.0);
        }}
    }}
    if (WALLS[p.y * PW + p.x] == 1) return vec4((p.x + p.y) % 2 == 0 ? pal(lap) : WHITE, 1.0);
    return vec4(0.0);
}}

void main() {{
    vec2 rs = RENDERSIZE;
    vec2 px = floor(gl_FragCoord.xy);
    px.y = rs.y - 1.0 - px.y;
    int scale = max(1, min(int(rs.x) / PW, int(rs.y) / PH));
    vec2 origin = floor((rs - vec2(float(PW * scale), float(PH * scale))) / 2.0);
    vec2 gp = floor((px - origin) / float(scale));
    if (gp.x < 0.0 || gp.y < 0.0 || gp.x >= float(PW) || gp.y >= float(PH)) {{
        gl_FragColor = vec4(0.0);
        return;
    }}
    float beatInBar = barBeat + TIME / max(XL_DURATION, 0.001) * max(beats, 0.01);
    float f = fract(beatInBar);
    float loud = clamp(texture(inputImage, vec2(0.5, 0.5)).x * energy, 0.0, 1.0);
    int dip = min(1, int(floor(loud * 1.5 * sin(3.14159 * f) + 0.5)));
    gl_FragColor = game(ivec2(gp), beatInBar, dip);
}}
"""


def maze_settings(path: str, start_step: int, kick: int, bar_beat: float, beats: float,
                  energy: float = 1.0) -> dict[str, str]:
    if not 0 < beats <= MAX_BEATS:
        raise ValueError(f"{beats} beats in one effect; the shader takes up to {MAX_BEATS}")
    if not 0 <= start_step <= MAX_STEP:
        raise ValueError(f"runner step {start_step} is past the shader's limit of {MAX_STEP:.0f}")
    return {
        "E_0FILEPICKERCTRL_IFS": path,
        "E_SLIDER_SHADERXYZZY_energy": str(int(round(energy * 100))),
        "E_SLIDER_SHADERXYZZY_kick": str(kick * 100),
        "E_SLIDER_SHADERXYZZY_startStep": str(start_step * 100),
        "E_SLIDER_SHADERXYZZY_barBeat": str(int(round(bar_beat * 100))),
        "E_SLIDER_SHADERXYZZY_beats": str(int(round(beats * 100))),
        "E_SLIDER_Shader_Speed": "100",
        "E_TEXTCTRL_Shader_LeadIn": "0",
        "E_TEXTCTRL_Shader_Offset_X": "0",
        "E_TEXTCTRL_Shader_Offset_Y": "0",
        "E_TEXTCTRL_Shader_Zoom": "0",
    }
