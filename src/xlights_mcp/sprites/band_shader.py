"""Generate the xLights ISF shader for the skeleton band (band.py), the band's counterpart of shader.py.

One Shader effect per bar (or a piece of one, around pictures). The placer passes
which 16th-note slots of the bar have a kick (kick) and a sung vowel (vocal) as 16-bit
masks, and where in the bar the effect starts (barBeat); the shader does the rest:
strums, stick hits, cymbal crash on beat 1, the singer's jaw and free arm, head bobs
that follow the song's loudness, and the optional stage.
"""

from __future__ import annotations

import json

from xlights_mcp.sprites import band as b
from xlights_mcp.sprites import dancers as d
from xlights_mcp.sprites.shader import FIGURE_LABELS, MAX_BEATS, _rgb, stage_glsl

SHADER_NAME = "Skeleton Band.fs"
CODES = ".BJSDWwMmCHhR"            # palette index of each layer character (0 = empty)
LAYER_NAMES = list(b.LAYERS)


def isf_header() -> dict:
    return {
        "DESCRIPTION": "xLights Audio2",
        "CREDIT": "xlights-mcp-server skeleton band (generated by sprites/band_shader.py)",
        "ISFVSN": "2",
        "CATEGORIES": ["xlights-mcp"],
        "INPUTS": [
            {"NAME": "inputImage", "TYPE": "image"},
            {"NAME": "figure", "LABEL": "Figure", "TYPE": "long", "DEFAULT": 0,
             "VALUES": [0, 1, 2], "LABELS": FIGURE_LABELS},
            {"NAME": "stage", "LABEL": "Stage", "TYPE": "bool", "DEFAULT": False},
            {"NAME": "energy", "LABEL": "Bounce to music", "TYPE": "float", "DEFAULT": 1.0, "MIN": 0.0, "MAX": 3.0},
            {"NAME": "kick", "LABEL": "Kick pattern (set by the tool)", "TYPE": "float", "DEFAULT": 4369.0,
             "MIN": 0.0, "MAX": 65535.0},
            {"NAME": "vocal", "LABEL": "Vocal pattern (set by the tool)", "TYPE": "float", "DEFAULT": 0.0,
             "MIN": 0.0, "MAX": 65535.0},
            {"NAME": "barBeat", "LABEL": "Start beat in bar", "TYPE": "float", "DEFAULT": 0.0, "MIN": 0.0, "MAX": 16.0},
            {"NAME": "beats", "LABEL": "Beats in effect", "TYPE": "float", "DEFAULT": 4.0, "MIN": 0.0,
             "MAX": float(MAX_BEATS)},
            {"NAME": "shirt1", "TYPE": "color", "DEFAULT": [0.59, 0.24, 0.9, 1.0]},
            {"NAME": "shirt2", "TYPE": "color", "DEFAULT": [0.94, 0.2, 0.08, 1.0]},
            {"NAME": "shirt3", "TYPE": "color", "DEFAULT": [0.08, 0.78, 0.75, 1.0]},
        ],
    }


def _layer_ints() -> list[int]:
    return [CODES.index(ch) for name in LAYER_NAMES for row in b.LAYERS[name] for ch in row]


def _li(name: str) -> int:
    return LAYER_NAMES.index(name)


def build_shader() -> str:
    header = json.dumps(isf_header(), indent=2)
    layers = _layer_ints()
    hair = [d.HAIR[h] for h in ("blonde", "pink", "auburn", "violet")]
    L = _li
    return f"""/*{header}*/

// Generated by xlights-mcp-server (src/xlights_mcp/sprites/band_shader.py). Edit the generator, not this file.

const int CELL = {b.W * b.H};
const int LAYERS[{len(layers)}] = int[]({", ".join(map(str, layers))});
const vec3 BONE = {_rgb(d.BONE)};
const vec3 JOINT = {_rgb(d.JOINT)};
const vec3 WOOD = {_rgb(b.WOOD)};
const vec3 WOOD_DARK = {_rgb(b.WOOD_DARK)};
const vec3 METAL = {_rgb(b.METAL)};
const vec3 METAL_DARK = {_rgb(b.METAL_DARK)};
const vec3 CYMBAL = {_rgb(b.CYMBAL)};
const vec3 CYMBAL_FLASH = {_rgb(b.CYMBAL_FLASH)};
const vec3 DRUM_HEAD = {_rgb(b.DRUM_HEAD)};
const vec3 DRUM_FLASH = {_rgb(b.DRUM_FLASH)};
const vec3 HAIR[4] = vec3[]({", ".join(_rgb(c) for c in hair)});

{stage_glsl()}

int code(int layer, vec2 p) {{
    return LAYERS[layer * CELL + int(p.y) * 13 + int(p.x)];
}}

bool bitOf(float mask, int slot) {{
    if (slot < 0 || slot > 15) return false;
    return ((int(mask + 0.5) >> slot) & 1) == 1;
}}

vec4 colourOf(int c, vec3 shirt, int slot, bool kicked) {{
    if (c == 1) return vec4(BONE, 1.0);
    if (c == 2) return vec4(JOINT, 1.0);
    if (c == 3 || c == 12) return vec4(shirt, 1.0);
    if (c == 4) return vec4(floor(floor(shirt * 255.0 + 0.5) * 0.6) / 255.0, 1.0);
    if (c == 5) return vec4(WOOD, 1.0);
    if (c == 6) return vec4(WOOD_DARK, 1.0);
    if (c == 7) return vec4(METAL, 1.0);
    if (c == 8) return vec4(METAL_DARK, 1.0);
    if (c == 9) return vec4(slot == 0 ? CYMBAL_FLASH : CYMBAL, 1.0);
    if (c == 10) return vec4(kicked ? DRUM_FLASH : DRUM_HEAD, 1.0);
    if (c == 11) return vec4(slot % 8 == 4 ? DRUM_FLASH : DRUM_HEAD, 1.0);
    return vec4(0.0);
}}

// The skull (with jaw, hair or headband); alpha 0 where the head does not draw. q is relative to the head top.
vec4 head(vec2 q, vec3 shirt, bool female, bool band, vec3 hair, bool openJaw) {{
    float x = q.x, y = q.y;
    if (y == 0.0 && x >= 4.0 && x <= 8.0) return vec4(female ? hair : (band ? shirt : BONE), 1.0);
    if (female && y == 0.0 && (x == 9.0 || x == 10.0)) return vec4(shirt, 1.0);
    if (openJaw) {{
        if (y == 4.0 && x >= 5.0 && x <= 7.0) return vec4(BONE, 1.0);
        if (y == 3.0 && (x == 5.0 || x == 7.0)) return vec4(BONE, 1.0);
        if (y == 2.0 && x == 6.0) return vec4(0.0, 0.0, 0.0, 2.0);           // open mouth: drawn black
    }} else if (y == 3.0 && x >= 5.0 && x <= 7.0) {{
        return vec4(BONE, 1.0);
    }}
    if (y == 2.0 && x >= 4.0 && x <= 8.0) return vec4(BONE, 1.0);
    if (y == 1.0 && (x == 4.0 || x == 6.0 || x == 8.0)) return vec4(BONE, 1.0);
    if (y == 1.0 && (x == 5.0 || x == 7.0)) return vec4(0.0, 0.0, 0.0, 2.0);  // eyes stay black over the body
    if (female && (x == 3.0 || x == 9.0) && y >= 1.0 && y <= 4.0) return vec4(hair, 1.0);
    return vec4(0.0);
}}

float dist2(vec3 a, vec3 b) {{
    vec3 d = (a - b) * 255.0;
    return dot(d, d);
}}

vec4 member(vec2 sp, int slot, bool kicked, bool sung, float loud, int bob) {{
    int j = int(sp.x) / 13;
    vec2 p = vec2(mod(sp.x, 13.0), sp.y);
    vec3 shirt = shirtOf(j);
    bool female = figure == 1 || (figure == 2 && j % 2 == 0);
    vec3 hair = HAIR[j % 4];
    for (int h = 0; h < 4; h++) {{
        if (dist2(hair, shirt) > 120.0 * 120.0) break;
        hair = HAIR[(j + h + 1) % 4];
    }}
    float headTop = (j == 2 ? {b.HEAD_Y["drums"]}.0 : 0.0) + float(bob);
    vec4 hd = head(p - vec2(0.0, headTop), shirt, female, j % 2 == 0, hair, j == 1 && sung);
    if (hd.a > 1.5) return vec4(0.0);
    if (hd.a > 0.0) return hd;
    int lay[4];
    int n;
    if (j == 0) {{
        lay[0] = {L("strum_down")}; if (slot % 4 >= 2) lay[0] = {L("strum_up")};
        lay[1] = {L("fret_arm")}; lay[2] = {L("guitar")}; lay[3] = {L("guitar_body")}; n = 4;
    }} else if (j == 1) {{
        lay[0] = loud < 0.35 ? {L("free_down")} : (loud < 0.7 ? {L("free_out")} : {L("free_up")});
        lay[1] = {L("singer_body")}; n = 2;
    }} else {{
        lay[0] = slot % 2 == 0 ? {L("hat_hit")} : {L("hat_up")};
        lay[1] = slot % 8 == 4 ? {L("snare_hit")} : {L("snare_up")};
        lay[2] = {L("kit")}; lay[3] = {L("drums_body")}; n = 4;
    }}
    for (int k = 0; k < 4; k++) {{
        if (k >= n) break;
        int c = code(lay[k], p);
        if (c > 0) return colourOf(c, shirt, slot, kicked);
    }}
    return vec4(0.0);
}}

void main() {{
    vec2 rs = RENDERSIZE;
    vec2 px = floor(gl_FragCoord.xy);
    px.y = rs.y - 1.0 - px.y;                 // y down, like the sprites
    int scale = max(1, min(int(rs.y) / 17, int(rs.x) / 39));
    vec2 crew = vec2(float(39 * scale), float(17 * scale));
    vec2 origin = stage ? vec2(floor((rs.x - crew.x) / 2.0), rs.y - crew.y) : floor((rs - crew) / 2.0);

    float beatInBar = barBeat + TIME / max(XL_DURATION, 0.001) * max(beats, 0.01);
    int slot = int(floor(beatInBar * {b.SLOTS_PER_BEAT}.0));
    int k0 = int(floor(beatInBar));
    float f0 = beatInBar - float(k0);
    float loud = clamp(texture(inputImage, vec2(0.5, 0.5)).x * energy, 0.0, 1.0);
    int bob = min(1, int(floor(loud * 1.5 * sin(3.14159 * f0) + 0.5)));

    vec4 c = vec4(0.0);
    vec2 sp = floor((px - origin) / float(scale));
    if (sp.x >= 0.0 && sp.y >= 0.0 && sp.x < 39.0 && sp.y < 17.0)
        c = member(sp, slot, bitOf(kick, slot), bitOf(vocal, slot), loud, bob);
    if (c.a == 0.0 && stage) c = stagePixel(px, rs, scale, origin, crew, 3, k0, f0 >= 0.5 ? 1 : 0);
    gl_FragColor = c;
}}
"""


def band_settings(path: str, figure: str, kick: int, vocal: int, bar_beat: float, beats: float,
                  energy: float = 1.0, stage: bool = False) -> dict[str, str]:
    if not 0 <= kick <= 0xFFFF or not 0 <= vocal <= 0xFFFF:
        raise ValueError("kick and vocal are 16-bit slot masks")
    if not 0 < beats <= MAX_BEATS:
        raise ValueError(f"{beats} beats in one effect; the shader takes up to {MAX_BEATS}")
    return {
        "E_0FILEPICKERCTRL_IFS": path,
        "E_CHOICE_SHADERXYZZY_figure": figure.title(),
        "E_CHECKBOX_SHADERXYZZY_stage": "1" if stage else "0",
        "E_SLIDER_SHADERXYZZY_energy": str(int(round(energy * 100))),
        "E_SLIDER_SHADERXYZZY_kick": str(kick * 100),
        "E_SLIDER_SHADERXYZZY_vocal": str(vocal * 100),
        "E_SLIDER_SHADERXYZZY_barBeat": str(int(round(bar_beat * 100))),
        "E_SLIDER_SHADERXYZZY_beats": str(int(round(beats * 100))),
        "E_SLIDER_Shader_Speed": "100",
        "E_TEXTCTRL_Shader_LeadIn": "0",
        "E_TEXTCTRL_Shader_Offset_X": "0",
        "E_TEXTCTRL_Shader_Offset_Y": "0",
        "E_TEXTCTRL_Shader_Zoom": "0",
    }
